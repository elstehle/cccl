// Stable warp-striped merge of two sorted runs — three methods, head-to-head.
//
// Contract (all methods): two sorted runs A, B of length S each, held WARP-STRIPED in one
// register pair per lane of an S-lane logical warp (lane q of the segment holds A[q] and B[q]);
// output is the stable merge (ties: A first; within-run order preserved), striped-2: lane q
// holds merged positions q and q+S. 32/S segments run concurrently per hardware warp.
//
//   M0 mp_smem       : shared-memory co-rank — each output position binary-searches its
//                      merge-path crossing in smem (the "existing approach" baseline).
//   M1 rank_bitonic  : bitonic merger on rank-augmented keys — lexicographic (key, input-rank)
//                      makes all elements distinct, so the oblivious network's output IS the
//                      stable merge. log2(2S) compare-exchange stages, 2 shuffles each (key+rank).
//   M2 ballot_route  : ballot-driven merge path — one (or two) warp ballots per level resolve
//                      the mid-diagonal crossings of ALL sub-problems at once (candidates for
//                      the monotone crossing predicate are distributed over lanes; the uniform
//                      ballot mask is decoded with popc under per-sub-problem masks, so the
//                      orchestration is pure ALU). The crossing COUNT enables stable routing:
//                      piece A stays, piece B shifts — order-preserving concatenation, so the
//                      recursion is stable by construction, no rank payload, no shared memory.
//
// Sizes: S in {4, 8, 16, 32} (merged output 8..64). Keys float; PAIRS variant carries an int
// value through the merge (stability is verified via values == std::merge reference).
// Methodology per DEVICE_SIDE_BENCHMARKING_ISSUE.md: data-dependent -> back-to-back random
// sorted inputs (generated by a segmented register scan), chain serialized on previous output,
// generate-only control subtracted; chain-length slope, clock64, min of reps. Throughput = one
// occupancy wave, element-normalized. Standalone: no cub includes.
//
// Modes: ./proto_ballot_merge [correct|lat|thr|all]

#include <algorithm>
#include <climits>
#include <cstdio>
#include <cstring>
#include <string>
#include <utility>
#include <vector>

__device__ int g_dcesink[16];

__device__ __forceinline__ float lcg_f(unsigned& s)
{
  s = 1664525u * s + 1013904223u;
  return (float) ((s >> 8) & 0xffffu) * (1.0f / 65536.0f);
}

__device__ __forceinline__ unsigned mask_width(int w)
{
  return (w >= 32) ? ~0u : ((1u << w) - 1);
}

__device__ __forceinline__ unsigned read_smid()
{
  unsigned x;
  asm("mov.u32 %0, %%smid;" : "=r"(x));
  return x;
}

template <int W>
__device__ __forceinline__ void sink_f(float (&v)[W])
{
  if (read_smid() == (unsigned) -1) // unprovable-false guard against DCE
  {
    float sum = 0.f;
#pragma unroll
    for (int i = 0; i < W; ++i)
    {
      sum += v[i];
    }
    *reinterpret_cast<float*>(g_dcesink) += sum;
  }
}

// segmented inclusive scan over S lanes -> strictly increasing (sorted) values from randoms
template <int S>
__device__ __forceinline__ float seg_scan(float x, int q)
{
#pragma unroll
  for (int d = 1; d < S; d <<= 1)
  {
    float t = __shfl_up_sync(~0u, x, d);
    if (q >= d)
    {
      x += t;
    }
  }
  return x;
}

// ------------------------------------------------------------------ M0: smem co-rank
template <int S, bool PAIRS>
__device__ __forceinline__ void merge_mp_smem(
  float a, float b, int va, int vb, float& o0, float& o1, int& w0, int& w1, float* smk, int* smv)
{
  const int lane = threadIdx.x & 31;
  const int q    = lane & (S - 1);
  smk[q]     = a;
  smk[S + q] = b;
  if (PAIRS)
  {
    smv[q]     = va;
    smv[S + q] = vb;
  }
  __syncwarp();
#pragma unroll
  for (int r = 0; r < 2; ++r)
  {
    const int p = r == 0 ? q : S + q;
    int lo      = p > S ? p - S : 0;
    int hi      = p < S ? p : S;
    while (lo < hi) // crossing c of diagonal p: #A-elements among first p outputs
    {
      const int mid = (lo + hi + 1) >> 1; // candidate c in (lo, hi]
      const float A = smk[mid - 1];
      const float B = smk[S + p - mid];
      if (!(B < A)) // A[c-1] <= B[p-c]: stable, A wins ties
      {
        lo = mid;
      }
      else
      {
        hi = mid - 1;
      }
    }
    const int c     = lo;
    const int j     = p - c;
    const bool takeA = (c < S) && ((j >= S) || !(smk[S + j] < smk[c]));
    const float ok  = takeA ? smk[c] : smk[S + j];
    const int ov    = PAIRS ? (takeA ? smv[c] : smv[S + j]) : 0;
    if (r == 0)
    {
      o0 = ok;
      w0 = ov;
    }
    else
    {
      o1 = ok;
      w1 = ov;
    }
  }
  __syncwarp(); // smem reusable by next call
}

// ------------------------------------------------------------------ M1: rank-augmented bitonic merger
template <int S, bool PAIRS>
__device__ __forceinline__ void
merge_rank_bitonic(float a, float b, int va, int vb, float& o0, float& o1, int& w0, int& w1)
{
  const int lane = threadIdx.x & 31;
  const int q    = lane & (S - 1);
  const int sb   = lane - q;
  // bitonic input: A ascending (ranks 0..S-1), reversed B descending (ranks 2S-1..S)
  float k0 = a;
  int r0   = q;
  int v0   = va;
  float k1 = __shfl_sync(~0u, b, sb + (S - 1 - q));
  int r1   = 2 * S - 1 - q;
  int v1   = PAIRS ? __shfl_sync(~0u, vb, sb + (S - 1 - q)) : 0;
  { // stage dist = S: same-lane exchange between virtual indices q and q+S
    const bool sw = (k1 < k0) || (k1 == k0 && r1 < r0);
    if (sw)
    {
      float tk = k0; k0 = k1; k1 = tk;
      int tr = r0; r0 = r1; r1 = tr;
      if (PAIRS) { int tv = v0; v0 = v1; v1 = tv; }
    }
  }
#pragma unroll
  for (int dist = S / 2; dist >= 1; dist >>= 1) // each register: independent bitonic sequence
  {
    const bool lower = (q & dist) == 0;
    {
      const float pk = __shfl_xor_sync(~0u, k0, dist);
      const int pr   = __shfl_xor_sync(~0u, r0, dist);
      const int pv   = PAIRS ? __shfl_xor_sync(~0u, v0, dist) : 0;
      const bool pl  = (pk < k0) || (pk == k0 && pr < r0);
      const bool take = lower ? pl : !pl;
      if (take) { k0 = pk; r0 = pr; if (PAIRS) { v0 = pv; } }
    }
    {
      const float pk = __shfl_xor_sync(~0u, k1, dist);
      const int pr   = __shfl_xor_sync(~0u, r1, dist);
      const int pv   = PAIRS ? __shfl_xor_sync(~0u, v1, dist) : 0;
      const bool pl  = (pk < k1) || (pk == k1 && pr < r1);
      const bool take = lower ? pl : !pl;
      if (take) { k1 = pk; r1 = pr; if (PAIRS) { v1 = pv; } }
    }
  }
  o0 = k0;
  o1 = k1;
  w0 = v0;
  w1 = v1;
}

// ------------------------------------------------------------------ M2: ballot-routed stable merge
// relative source position within a sub-problem (base-relative): position s of the (size)-wide
// sub-problem with piece1 length b and mid-crossing c
__device__ __forceinline__ int route_src(int s, int b, int half, int c)
{
  if (s < half)
  {
    return (s < c) ? s : b + (s - c); // low half = piece1[0..c) ++ piece2[0..half-c)
  }
  const int t = s - half;
  return (t < b - c) ? (c + t) : s; // high half = piece1[c..b) ++ piece2[half-c..): tail stays in place
}

template <int S, bool PAIRS>
__device__ __forceinline__ void
merge_ballot(float a, float b, int va, int vb, float& o0, float& o1, int& w0, int& w1)
{
  const int lane           = threadIdx.x & 31;
  const int q              = lane & (S - 1);
  const int sb             = lane - q;
  const unsigned segmask_S = mask_width(S) << sb;

  float e0 = a, e1 = b;
  int u0 = va, u1 = vb;
  int bnd0, bnd1; // piece1 length of the sub-problem containing position q / q+S

  { // ---- level 1: one sub-problem [0, 2S), piece1 = A (len S). Candidate c = q+1 on lane q.
    // pred(c): A[c-1] <= B[S-c]  ->  A[q] (own) vs B[S-1-q]
    const float Bp     = __shfl_sync(~0u, e1, sb + (S - 1 - q));
    const unsigned bal = __ballot_sync(~0u, !(Bp < e0));
    const int c        = __popc(bal & segmask_S); // crossing of the middle diagonal
    // route position q:   (q < c)     ? A[q] (own)      : B[q - c]
    //       position S+q: (q < S - c) ? A[c + q]        : B[q] (own)
    const int lB   = max(q - c, 0);
    const int lA   = min(c + q, S - 1);
    const float fB = __shfl_sync(~0u, e1, sb + lB);
    const float fA = __shfl_sync(~0u, e0, sb + lA);
    const int gB   = PAIRS ? __shfl_sync(~0u, u1, sb + lB) : 0;
    const int gA   = PAIRS ? __shfl_sync(~0u, u0, sb + lA) : 0;
    const float n0 = (q < c) ? e0 : fB;
    const float n1 = (q < S - c) ? fA : e1;
    const int m0   = (q < c) ? u0 : gB;
    const int m1   = (q < S - c) ? gA : u1;
    e0   = n0;
    e1   = n1;
    u0   = m0;
    u1   = m1;
    bnd0 = c;     // sub-problem [0,S):  piece1 = A[0..c)
    bnd1 = S - c; // sub-problem [S,2S): piece1 = A[c..S)
  }

#pragma unroll
  for (int size = S; size >= 2; size >>= 1) // ---- levels 2..log2(2S): sub-problems within one register
  {
    const int half  = size >> 1;
    const int base  = q & ~(size - 1); // same offset for p0's and p1's sub-problems
    const int s     = q - base;
    // role 0 (position q, register e0): candidate c0 = lo0+1+s if s < hi0-lo0
    const int lo0   = max(0, half - (size - bnd0));
    const int hi0   = min(half, bnd0);
    const bool act0 = s < (hi0 - lo0);
    const int c0    = lo0 + 1 + s;
    const int pA0   = min(base + c0 - 1, base + size - 1);
    const int pB0   = min(max(base + bnd0 + half - c0, base), base + size - 1);
    const float A0  = __shfl_sync(~0u, e0, sb + pA0);
    const float B0  = __shfl_sync(~0u, e0, sb + pB0);
    // role 1 (position S+q, register e1): same slot arithmetic, boundaries bnd1
    const int lo1   = max(0, half - (size - bnd1));
    const int hi1   = min(half, bnd1);
    const bool act1 = s < (hi1 - lo1);
    const int c1    = lo1 + 1 + s;
    const int pA1   = min(base + c1 - 1, base + size - 1);
    const int pB1   = min(max(base + bnd1 + half - c1, base), base + size - 1);
    const float A1  = __shfl_sync(~0u, e1, sb + pA1);
    const float B1  = __shfl_sync(~0u, e1, sb + pB1);

    const unsigned bal0 = __ballot_sync(~0u, act0 && !(B0 < A0));
    const unsigned bal1 = __ballot_sync(~0u, act1 && !(B1 < A1));
    const unsigned spm  = mask_width(half) << (sb + base); // my sub-problem's candidate lanes
    const int cs0       = lo0 + __popc(bal0 & spm);
    const int cs1       = lo1 + __popc(bal1 & spm);

    const int src0 = base + route_src(s, bnd0, half, cs0);
    const int src1 = base + route_src(s, bnd1, half, cs1);
    const float n0 = __shfl_sync(~0u, e0, sb + src0);
    const float n1 = __shfl_sync(~0u, e1, sb + src1);
    const int m0   = PAIRS ? __shfl_sync(~0u, u0, sb + src0) : 0;
    const int m1   = PAIRS ? __shfl_sync(~0u, u1, sb + src1) : 0;
    e0 = n0;
    e1 = n1;
    u0 = m0;
    u1 = m1;
    bnd0 = (s < half) ? cs0 : (bnd0 - cs0);
    bnd1 = (s < half) ? cs1 : (bnd1 - cs1);
  }
  o0 = e0;
  o1 = e1;
  w0 = u0;
  w1 = u1;
}

// ------------------------------------------------------------------ dispatch
template <int S, int METHOD, bool PAIRS>
__device__ __forceinline__ void do_merge(
  float a, float b, int va, int vb, float& o0, float& o1, int& w0, int& w1, float* smk, int* smv)
{
  if constexpr (METHOD == 0)
  {
    merge_mp_smem<S, PAIRS>(a, b, va, vb, o0, o1, w0, w1, smk, smv);
  }
  else if constexpr (METHOD == 1)
  {
    merge_rank_bitonic<S, PAIRS>(a, b, va, vb, o0, o1, w0, w1);
  }
  else
  {
    merge_ballot<S, PAIRS>(a, b, va, vb, o0, o1, w0, w1);
  }
}

// ------------------------------------------------------------------ correctness
template <int S, int METHOD>
__global__ void correct_k(const float* ink, const int* inv, float* outk, int* outv)
{
  const int lane = threadIdx.x & 31;
  const int q    = lane & (S - 1);
  const int seg  = (lane - q) / S;
  __shared__ float SMK[64];
  __shared__ int SMV[64];
  const float a = ink[seg * 2 * S + q];
  const float b = ink[seg * 2 * S + S + q];
  const int va  = inv[seg * 2 * S + q];
  const int vb  = inv[seg * 2 * S + S + q];
  float o0, o1;
  int w0, w1;
  do_merge<S, METHOD, true>(a, b, va, vb, o0, o1, w0, w1, &SMK[seg * 2 * S], &SMV[seg * 2 * S]);
  outk[seg * 2 * S + q]     = o0;
  outk[seg * 2 * S + S + q] = o1;
  outv[seg * 2 * S + q]     = w0;
  outv[seg * 2 * S + S + q] = w1;
}

// ------------------------------------------------------------------ latency
constexpr int kLatReps = 32;

template <int S, int METHOD, bool PAIRS, int DO_MERGE>
__global__ void __launch_bounds__(32) lat_k(unsigned seed0, int chain, long long* out)
{
  const int lane = threadIdx.x & 31;
  const int q    = lane & (S - 1);
  const int seg  = (lane - q) / S;
  __shared__ float SMK[64];
  __shared__ int SMV[64];
  unsigned s     = seed0 + (lane + 7) * 2654435761u;
  float o0 = 0.f, o1 = 0.f;
  int w0 = 0, w1 = 0;
  long long best = LLONG_MAX;
#pragma unroll 1
  for (int rep = 0; rep < kLatReps; ++rep)
  {
    __syncwarp();
    long long t0 = clock64();
    asm volatile("" ::: "memory");
#pragma unroll 1
    for (int n = 0; n < chain; ++n)
    {
      // serialize chain on previous output; mix in n against any idempotence collapse
      unsigned ss = s ^ __float_as_uint(o0) ^ (unsigned) (n * 2654435761u);
      const float a = seg_scan<S>(lcg_f(ss), q);
      const float b = seg_scan<S>(lcg_f(ss), q);
      if (DO_MERGE)
      {
        do_merge<S, METHOD, PAIRS>(a, b, q, S + q, o0, o1, w0, w1, &SMK[seg * 2 * S], &SMV[seg * 2 * S]);
      }
      else
      {
        o0 = a;
        o1 = b;
      }
    }
    // sink (unprovable memory side effect) anchors register-only methods against DCE/hoisting;
    // a bare empty-asm register consume is not sufficient (measured 0.0 for the shuffle-only paths)
    float cv[2] = {o0 + (float) w0, o1 + (float) w1};
    sink_f(cv);
    asm volatile("" ::: "memory");
    long long t1 = clock64();
    best         = ::min(best, t1 - t0);
  }
  if (lane == 0)
  {
    *out = best;
  }
}

// ------------------------------------------------------------------ throughput
constexpr int kThrBlock = 128;
constexpr int kThrIters = 200;

template <int S, int METHOD, bool PAIRS>
__global__ void __launch_bounds__(kThrBlock) thr_k(int num_iter)
{
  const int lane = threadIdx.x & 31;
  const int warp = threadIdx.x >> 5;
  const int q    = lane & (S - 1);
  const int seg  = (lane - q) / S;
  __shared__ float SMK[kThrBlock / 32][64];
  __shared__ int SMV[kThrBlock / 32][64];
  unsigned s = 12345u + (threadIdx.x + 7) * 2654435761u;
  float o0 = 0.f, o1 = 0.f;
  int w0 = 0, w1 = 0;
#pragma unroll 1
  for (int iter = 0; iter < num_iter; ++iter)
  {
    unsigned ss   = s + iter * 2654435761u;
    const float a = seg_scan<S>(lcg_f(ss), q);
    const float b = seg_scan<S>(lcg_f(ss), q);
    do_merge<S, METHOD, PAIRS>(a, b, q, S + q, o0, o1, w0, w1, &SMK[warp][seg * 2 * S], &SMV[warp][seg * 2 * S]);
    // values must be consumed too, or the pairs variant's value shuffles get dead-code-eliminated
    float v[2] = {o0 + (float) w0, o1 + (float) w1};
    sink_f(v);
  }
}

