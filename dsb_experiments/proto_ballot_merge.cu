static void fit(const double* x, const double* y, int m, double& a, double& b)
{
  double sx = 0, sy = 0, sxx = 0, sxy = 0;
  for (int i = 0; i < m; ++i)
  {
    sx += x[i];
    sy += y[i];
    sxx += x[i] * x[i];
    sxy += x[i] * y[i];
  }
  b = (m * sxy - sx * sy) / (m * sxx - sx * sx);
  a = (sy - b * sx) / m;
}

// build one segment's two sorted runs; pattern selects tie structure
static void gen_runs(std::vector<float>& k, int S, unsigned seed, int pattern)
{
  k.resize(2 * S);
  unsigned s = seed;
  auto rnd   = [&]() {
    s = 1664525u * s + 1013904223u;
    return (s >> 8) & 0xffffu;
  };
  for (int i = 0; i < 2 * S; ++i)
  {
    switch (pattern)
    {
      case 0: k[i] = (float) rnd(); break;            // random
      case 1: k[i] = (float) (rnd() % 4); break;      // heavy ties
      case 2: k[i] = 1.f; break;                      // all equal
      case 3: k[i] = (float) (i < S ? rnd() % 100 : 1000 + rnd() % 100); break; // A << B
      case 4: k[i] = (float) (i < S ? 1000 + rnd() % 100 : rnd() % 100); break; // B << A
    }
  }
  std::sort(k.begin(), k.begin() + S);
  std::sort(k.begin() + S, k.end());
}

template <int S, int METHOD>
static bool check_one(unsigned seed, int pattern)
{
  const int SEGS = 32 / S;
  std::vector<float> ink(SEGS * 2 * S);
  std::vector<int> inv(SEGS * 2 * S);
  for (int g = 0; g < SEGS; ++g)
  {
    std::vector<float> k;
    gen_runs(k, S, seed + g * 977u, pattern);
    for (int i = 0; i < 2 * S; ++i)
    {
      ink[g * 2 * S + i] = k[i];
      inv[g * 2 * S + i] = i; // identity values expose stability
    }
  }
  float *d_ik, *d_ok;
  int *d_iv, *d_ov;
  CHECK(cudaMalloc(&d_ik, ink.size() * 4));
  CHECK(cudaMalloc(&d_ok, ink.size() * 4));
  CHECK(cudaMalloc(&d_iv, inv.size() * 4));
  CHECK(cudaMalloc(&d_ov, inv.size() * 4));
  CHECK(cudaMemcpy(d_ik, ink.data(), ink.size() * 4, cudaMemcpyHostToDevice));
  CHECK(cudaMemcpy(d_iv, inv.data(), inv.size() * 4, cudaMemcpyHostToDevice));
  correct_k<S, METHOD><<<1, 32>>>(d_ik, d_iv, d_ok, d_ov);
  CHECK(cudaDeviceSynchronize());
  std::vector<float> ok(ink.size());
  std::vector<int> ov(inv.size());
  CHECK(cudaMemcpy(ok.data(), d_ok, ok.size() * 4, cudaMemcpyDeviceToHost));
  CHECK(cudaMemcpy(ov.data(), d_ov, ov.size() * 4, cudaMemcpyDeviceToHost));
  cudaFree(d_ik);
  cudaFree(d_ok);
  cudaFree(d_iv);
  cudaFree(d_ov);
  for (int g = 0; g < SEGS; ++g)
  {
    // reference: std::merge is stable and takes from the first range on ties
    std::vector<std::pair<float, int>> A, B, ref(2 * S);
    for (int i = 0; i < S; ++i)
    {
      A.push_back({ink[g * 2 * S + i], i});
      B.push_back({ink[g * 2 * S + S + i], S + i});
    }
    std::merge(A.begin(), A.end(), B.begin(), B.end(), ref.begin(), [](const auto& x, const auto& y) {
      return x.first < y.first;
    });
    for (int p = 0; p < 2 * S; ++p)
    {
      if (ok[g * 2 * S + p] != ref[p].first || ov[g * 2 * S + p] != ref[p].second)
      {
        printf("      seg %d pos %d: got (%g,%d) want (%g,%d)\n",
               g, p, ok[g * 2 * S + p], ov[g * 2 * S + p], ref[p].first, ref[p].second);
        return false;
      }
    }
  }
  return true;
}

template <int S, int METHOD>
static bool check_method()
{
  bool ok = true;
  for (int pat = 0; pat <= 4; ++pat)
  {
    for (unsigned t = 0; t < (pat <= 1 ? 12u : 2u); ++t)
    {
      ok = ok && check_one<S, METHOD>(4242u + t * 131u + pat * 7919u, pat);
    }
  }
  return ok;
}

template <int S, int METHOD, bool PAIRS, int DO>
static double slope_raw()
{
  long long* d;
  CHECK(cudaMalloc(&d, sizeof(long long)));
  const int chains[] = {1, 2, 4, 8, 16};
  double x[5], y[5];
  for (int i = 0; i < 5; ++i)
  {
    lat_k<S, METHOD, PAIRS, DO><<<1, 32>>>(12345u, chains[i], d);
    CHECK(cudaDeviceSynchronize());
    long long c;
    CHECK(cudaMemcpy(&c, d, sizeof c, cudaMemcpyDeviceToHost));
    x[i] = chains[i];
    y[i] = (double) c;
  }
  double a, b;
  fit(x, y, 5, a, b);
  cudaFree(d);
  return b;
}

template <int S, int METHOD, bool PAIRS>
static double thr_gelems(int num_SMs)
{
  int maxblk = 0;
  CHECK(cudaOccupancyMaxActiveBlocksPerMultiprocessor(&maxblk, thr_k<S, METHOD, PAIRS>, kThrBlock, 0));
  const int grid = maxblk * num_SMs;
  thr_k<S, METHOD, PAIRS><<<grid, kThrBlock>>>(kThrIters);
  CHECK(cudaDeviceSynchronize());
  cudaEvent_t e0, e1;
  cudaEventCreate(&e0);
  cudaEventCreate(&e1);
  float best_ms = 1e30f;
  for (int rep = 0; rep < 5; ++rep)
  {
    cudaEventRecord(e0);
    thr_k<S, METHOD, PAIRS><<<grid, kThrBlock>>>(kThrIters);
    cudaEventRecord(e1);
    CHECK(cudaDeviceSynchronize());
    float ms;
    cudaEventElapsedTime(&ms, e0, e1);
    best_ms = std::min(best_ms, ms);
  }
  cudaEventDestroy(e0);
  cudaEventDestroy(e1);
  // 64 merged elements per hardware warp per iteration (all segments together)
  const double elems = (double) grid * (kThrBlock / 32) * kThrIters * 64.0;
  return elems / (best_ms * 1e-3) / 1e9;
}

template <int S>
static void run_correct()
{
  const bool m0 = check_method<S, 0>();
  const bool m1 = check_method<S, 1>();
  const bool m2 = check_method<S, 2>();
  printf("  S=%2d (2x%2d -> %2d):  mp_smem %s   rank_bitonic %s   ballot_route %s\n",
         S, S, 2 * S, m0 ? "PASS" : "FAIL", m1 ? "PASS" : "FAIL", m2 ? "PASS" : "FAIL");
}

template <int S, bool PAIRS>
static void run_lat()
{
  const double gen = slope_raw<S, 0, PAIRS, 0>();
  const double m0  = slope_raw<S, 0, PAIRS, 1>() - gen;
  const double m1  = slope_raw<S, 1, PAIRS, 1>() - gen;
  const double m2  = slope_raw<S, 2, PAIRS, 1>() - gen;
  printf("  %s S=%2d:  mp_smem=%7.1f   rank_bitonic=%7.1f   ballot_route=%7.1f   (best: %s)\n",
         PAIRS ? "pairs" : "keys ", S, m0, m1, m2,
         (m1 <= m0 && m1 <= m2) ? "rank_bitonic" : (m2 <= m0 ? "ballot_route" : "mp_smem"));
}

template <int S, bool PAIRS>
static void run_thr(int num_SMs)
{
  const double m0 = thr_gelems<S, 0, PAIRS>(num_SMs);
  const double m1 = thr_gelems<S, 1, PAIRS>(num_SMs);
  const double m2 = thr_gelems<S, 2, PAIRS>(num_SMs);
  printf("  %s S=%2d:  mp_smem=%7.1f   rank_bitonic=%7.1f   ballot_route=%7.1f  Gelem/s\n",
         PAIRS ? "pairs" : "keys ", S, m0, m1, m2);
}

#define FOR_S(X) X(4) X(8) X(16) X(32)

int main(int argc, char** argv)
{
  std::string mode = argc > 1 ? argv[1] : "all";
  cudaDeviceProp p;
  cudaGetDeviceProperties(&p, 0);
  printf("device: %s (sm_%d%d, %d SMs)\n", p.name, p.major, p.minor, p.multiProcessorCount);
  if (mode == "correct" || mode == "all")
  {
    printf("\n=== correctness + stability vs std::merge (patterns: random/ties/equal/A<B/B<A) ===\n");
#define C(S) run_correct<S>();
    FOR_S(C)
  }
  if (mode == "lat" || mode == "all")
  {
    printf("\n=== LATENCY: slope cyc per warp-call (32/S concurrent segment merges; gen-subtracted) ===\n");
#define LK(S) run_lat<S, false>();
    FOR_S(LK)
#define LP(S) run_lat<S, true>();
    FOR_S(LP)
  }
  if (mode == "thr" || mode == "all")
  {
    printf("\n=== THROUGHPUT: one occupancy wave, Gelem/s (64 merged elems / warp-iter) ===\n");
#define TK(S) run_thr<S, false>(p.multiProcessorCount);
    FOR_S(TK)
#define TP(S) run_thr<S, true>(p.multiProcessorCount);
    FOR_S(TP)
  }
  return 0;
}
