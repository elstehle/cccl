#!/usr/bin/env python3
"""Node-side driver for the topk_swarm harness.

Generates one translation unit per cell (variant adapter plus control adapter), compiles them in
parallel outside the GPU lock, runs canary, all cells and canary again inside one flock section on
the GPU lock file, merges the per-cell JSON into one batch file under <out>/, and refines the
resource fields from `nvcc -Xptxas -v` and `cuobjdump -sass`.

Typical call on a node (see harness/README.md):

  python3 run.py --repo <root>/cccl --root <root> --holder eval-engineer --gpu 0 \
      --adapter B1_reference --control B1_reference --cells cells_focus.json \
      --keys fp32,bf16 --label focus_b200

Only the Python standard library is required.
"""
import argparse
import concurrent.futures
import datetime
import fcntl
import itertools
import json
import os
import re
import shlex
import socket
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))

KEY_CPP = {"fp32": "float", "bf16": "__nv_bfloat16", "fp16": "__half", "fp64": "double"}
REQ_CPP = {
    "not_guaranteed": "topk::requirement::not_guaranteed",
    "prefer_smaller_index": "topk::requirement::prefer_smaller_index",
    "prefer_larger_index": "topk::requirement::prefer_larger_index",
}

TU_TEMPLATE = """// generated by run.py, do not edit
#include "topk_harness.cuh"
#include "adapters/{variant}.cuh"
{control_include}
int main(int argc, char** argv)
{{
  return topk::run_cell<{variant}_info, {variant}, {control}_info, {control}, {key}, {threads}, {n}, {k}, {req}, {creq}>(argc, argv);
}}
"""


def log(msg):
    sys.stdout.write(msg.rstrip("\n") + "\n")
    sys.stdout.flush()


def utc_now():
    return datetime.datetime.now(datetime.timezone.utc)


def read_adapter_meta(header_path):
    """scope, id and data_dependent from the <id>_info struct of an adapter header."""
    text = open(header_path).read()
    m = re.search(r"topk::scope\s+scope\s*=\s*topk::scope::(\w+)", text)
    if not m:
        raise SystemExit("cannot find `topk::scope scope = topk::scope::<x>` in %s" % header_path)
    dd = re.search(r"data_dependent\s*=\s*(true|false)", text)
    ident = re.search(r'id\s*=\s*"([^"]+)"', text)
    return {
        "scope": m.group(1),
        "data_dependent": (dd.group(1) == "true") if dd else None,
        "id": ident.group(1) if ident else os.path.splitext(os.path.basename(header_path))[0],
        "header": header_path,
    }


def expand_cells(spec, scope, args):
    sc = spec["scopes"][scope]
    keys = args.keys.split(",") if args.keys else spec["key_types"]
    reqs = args.req.split(",") if args.req else spec["requirements"]
    ns = [int(x) for x in args.n.split(",")] if args.n else sc["n"]
    ks = [int(x) for x in args.k.split(",")] if args.k else spec["k_values"]
    threads = [int(x) for x in args.threads.split(",")] if args.threads else sc["threads"]
    frac = spec.get("k_max_fraction", 0.5)
    k_by_n = {int(a): b for a, b in spec.get("k_by_n", {}).items()}
    cells = []
    for key, t, n, k, req in itertools.product(keys, threads, ns, ks, reqs):
        if n < t or k > n * frac:
            continue
        if n in k_by_n and k not in k_by_n[n]:
            continue
        cells.append({"key_type": key, "threads": t, "n": n, "k": k, "requirement": req})
    return cells


def expand_named_cells(path, scope, args, default_threads):
    """Cells from ideas/named_cells.json (one object per workload) for one scope. regime and
    requirement "both" expand to the two focus values. threads defaults to the scope's first
    thread count (subwarp cells need an explicit "threads" or get the smallest logical warp that
    divides n). Cells whose n is not a multiple of the thread count are skipped and reported."""
    data = json.load(open(path))
    items = data if isinstance(data, list) else data.get("cells", [])
    keys = args.keys.split(",") if args.keys else None
    reqs = args.req.split(",") if args.req else None
    cells, skipped = [], []
    for it in items:
        if it.get("scope") != scope:
            continue
        if keys and it.get("key_type") not in keys:
            continue
        n, k = int(it["n"]), int(it["k"])
        t = int(it.get("threads", 0)) or default_threads.get(scope, 32)
        if scope == "subwarp" and not it.get("threads"):
            t = next((x for x in (4, 8, 16) if n % x == 0 and n >= x and n // x <= 32), 0)
        if t == 0 or n % t != 0 or n < t:
            skipped.append((it.get("name"), "n %d is not a multiple of %d threads" % (n, t)))
            continue
        req_list = ["not_guaranteed", "prefer_smaller_index"] if it.get("requirement") == "both" else [it["requirement"]]
        if reqs:
            req_list = [r for r in req_list if r in reqs]
        for req in req_list:
            cells.append({"key_type": it["key_type"], "threads": t, "n": n, "k": k, "requirement": req,
                          "workload_name": it.get("name"), "named_regime": it.get("regime", "both")})
    return cells, skipped


def cell_name(variant, control, c, control_req=None, runs=0):
    ctrl = control + ("@" + control_req if control_req and control_req != c["requirement"] else "")
    base = "%s__%s__%s_T%d_N%d_K%d_%s" % (variant, ctrl, c["key_type"], c["threads"], c["n"], c["k"],
                                         c["requirement"])
    if runs and runs > 1:
        base += "_runs%d" % runs
    return base + ("__" + c["workload_name"]) if c.get("workload_name") else base


def nvcc_version(nvcc):
    try:
        out = subprocess.run([nvcc, "--version"], capture_output=True, text=True, timeout=60).stdout
    except Exception:
        return "unknown"
    m = re.search(r"release\s+([\d.]+),\s*V([\d.]+)", out)
    return m.group(2) if m else "unknown"


def git_info(repo):
    def run(cmd):
        try:
            return subprocess.run(cmd, capture_output=True, text=True, timeout=60, cwd=repo).stdout.strip()
        except Exception:
            return ""

    return {
        "path": repo,
        "commit": run(["git", "rev-parse", "HEAD"]),
        "branch": run(["git", "rev-parse", "--abbrev-ref", "HEAD"]),
        "dirty": bool(run(["git", "status", "--porcelain", "--untracked-files=no"])),
    }


def compile_one(nvcc, arch, repo, harness_dir, src, binary, logfile, timeout, extra_flags):
    cmd = [nvcc, "-std=c++17", "-O3", "-arch=" + arch,
           "-I" + os.path.join(repo, "cub"), "-I" + os.path.join(repo, "libcudacxx", "include"),
           "-I" + os.path.join(repo, "thrust"), "-I" + harness_dir, "-Xptxas", "-v"] + extra_flags + \
          ["-o", binary, src]
    t0 = time.time()
    status = "ok"
    try:
        with open(logfile, "w") as lf:
            lf.write("$ " + " ".join(shlex.quote(c) for c in cmd) + "\n")
            lf.flush()
            r = subprocess.run(cmd, stdout=lf, stderr=subprocess.STDOUT, timeout=timeout)
        if r.returncode != 0:
            status = "compile_error"
    except subprocess.TimeoutExpired:
        status = "compile_timeout"
    return {"status": status, "seconds": round(time.time() - t0, 1), "log": logfile, "cmd": cmd}


def parse_ptxas(logfile):
    """Per mangled kernel symbol: registers, stack, spill stores and loads (from -Xptxas -v)."""
    res = {}
    cur = None
    try:
        lines = open(logfile, errors="replace").read().splitlines()
    except OSError:
        return res
    for ln in lines:
        m = re.search(r"Function properties for (\S+)", ln)
        if m:
            cur = m.group(1)
            res.setdefault(cur, {})
            continue
        m = re.search(r"Compiling entry function '([^']+)'", ln)
        if m:
            cur = m.group(1)
            res.setdefault(cur, {})
            continue
        m = re.search(r"(\d+) bytes stack frame, (\d+) bytes spill stores, (\d+) bytes spill loads", ln)
        if m and cur:
            res[cur].update(stack_bytes=int(m.group(1)), spill_stores=int(m.group(2)), spill_loads=int(m.group(3)))
            continue
        m = re.search(r"Used (\d+) registers", ln)
        if m and cur:
            res[cur]["registers"] = int(m.group(1))
    return res


def sass_stats(cuobjdump, binary, timeout=600):
    """Per function: STL, LDL, BAR.SYNC and total instruction counts from cuobjdump -sass."""
    stats = {}
    try:
        out = subprocess.run([cuobjdump, "-sass", binary], capture_output=True, text=True, timeout=timeout).stdout
    except Exception:
        return stats
    cur = None
    for ln in out.splitlines():
        m = re.search(r"Function\s*:\s*(\S+)", ln)
        if m:
            cur = m.group(1)
            stats[cur] = {"stl_count": 0, "ldl_count": 0, "bar_sync_count": 0, "bssy_count": 0, "sass_instructions": 0}
            continue
        if cur and re.match(r"\s*/\*[0-9a-f]+\*/", ln):
            stats[cur]["sass_instructions"] += 1
            if re.search(r"\bSTL\b", ln):
                stats[cur]["stl_count"] += 1
            if re.search(r"\bLDL\b", ln):
                stats[cur]["ldl_count"] += 1
            if re.search(r"\bBAR\.SYNC", ln):
                stats[cur]["bar_sync_count"] += 1
            if re.search(r"\bBSSY\b", ln):
                stats[cur]["bssy_count"] += 1
    return stats


def refine_resources(res, ptxas, sass):
    sym = res.get("kernel_symbol", "")
    p = ptxas.get(sym)
    if p:
        if "spill_stores" in p:
            res["spill_bytes"] = p["spill_stores"] + p["spill_loads"]
            res["spill_stores"] = p["spill_stores"]
            res["spill_loads"] = p["spill_loads"]
            res["stack_bytes"] = p.get("stack_bytes", 0)
        if "registers" in p:
            res["registers_ptxas"] = p["registers"]
    s = sass.get(sym)
    if s:
        res.update(s)
    return res


class GpuLock:
    """Exclusive flock(2) on the per-GPU lock file, same semantics as `flock <file> -c ...`."""

    def __init__(self, path):
        self.path = path
        self.fd = None

    def __enter__(self):
        if not self.path:
            return self
        os.makedirs(os.path.dirname(self.path) or ".", exist_ok=True)
        self.fd = open(self.path, "a+")
        t0 = time.time()
        while True:
            try:
                fcntl.flock(self.fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except BlockingIOError:
                if time.time() - t0 > 3600 * 3:
                    raise SystemExit("could not acquire %s within 3 hours" % self.path)
                time.sleep(5)
        log("lock acquired: %s (waited %.0f s)" % (self.path, time.time() - t0))
        return self

    def __exit__(self, *a):
        if self.fd:
            fcntl.flock(self.fd, fcntl.LOCK_UN)
            self.fd.close()
            log("lock released: %s" % self.path)


def run_binary(binary, extra, logfile, timeout, env):
    cmd = [binary] + extra
    t0 = time.time()
    status = "ok"
    try:
        with open(logfile, "a") as lf:
            lf.write("$ " + " ".join(shlex.quote(c) for c in cmd) + "\n")
            lf.flush()
            r = subprocess.run(cmd, stdout=lf, stderr=subprocess.STDOUT, timeout=timeout, env=env)
        if r.returncode != 0:
            status = "run_error_%d" % r.returncode
    except subprocess.TimeoutExpired:
        status = "run_timeout"
    return status, round(time.time() - t0, 1)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", required=True, help="CCCL checkout (cub, libcudacxx, thrust include roots)")
    ap.add_argument("--harness", default=HERE, help="harness directory (this directory)")
    ap.add_argument("--root", help="on-node root: derives --work, --out and --lock when they are not given")
    ap.add_argument("--holder", default=os.environ.get("USER", "unknown"))
    ap.add_argument("--work", help="scratch for generated sources, binaries and logs")
    ap.add_argument("--out", help="directory for the batch JSON")
    ap.add_argument("--lock", help="per-GPU lock file, measurements run under flock on it")
    ap.add_argument("--gpu", type=int, default=0, help="GPU index, sets CUDA_VISIBLE_DEVICES")
    ap.add_argument("--adapter", required=True, help="variant adapter id (header adapters/<id>.cuh)")
    ap.add_argument("--control", help="control adapter id (default: the variant itself, an A/A control)")
    ap.add_argument("--control-req", help="requirement the control is instantiated with when it differs from the "
                    "variant's (e.g. not_guaranteed, so a prefer_smaller_index variant runs against the reference's "
                    "not_guaranteed path in the same lock section)")
    ap.add_argument("--cells", default=os.path.join(HERE, "cells_focus.json"))
    ap.add_argument("--named-cells", help="ideas/named_cells.json: run these workload cells instead of the grid")
    ap.add_argument("--cell-list", help="JSON list of explicit cells [{key_type, threads, n, k, requirement}] instead "
                    "of the grid (e.g. the close cells a winners pass selects for the tie_heavy pattern)")
    ap.add_argument("--check-sorted", action="store_true", help="phase 3b: the oracle also checks the output order")
    ap.add_argument("--keys", help="comma list, subset of the cells file")
    ap.add_argument("--req", help="comma list of requirements")
    ap.add_argument("--n", help="comma list of N")
    ap.add_argument("--k", help="comma list of k")
    ap.add_argument("--threads", help="comma list of thread counts")
    ap.add_argument("--patterns", default="random", help="comma list of input patterns to measure")
    ap.add_argument("--regimes", default="latency,throughput")
    ap.add_argument("--seeds", type=int, default=4, help="oracle seeds for the cell's pattern")
    ap.add_argument("--runs", type=int, default=0, help="M: every input row is M consecutive runs sorted by (key "
                    "descending, index ascending), applied to the cell pattern and the battery (sorted-runs merge inputs)")
    ap.add_argument("--no-battery", action="store_true", help="oracle on the cell pattern only")
    ap.add_argument("--oracle-only", action="store_true")
    ap.add_argument("--arch", default="sm_100")
    ap.add_argument("--nvcc", default=os.environ.get("NVCC", "nvcc"))
    ap.add_argument("--cuobjdump", default=os.environ.get("CUOBJDUMP", "cuobjdump"))
    ap.add_argument("--extra-flags", default="", help="extra nvcc flags, shell-quoted string")
    ap.add_argument("--jobs", type=int, default=min(16, os.cpu_count() or 4))
    ap.add_argument("--timeout-compile", type=int, default=2400)
    ap.add_argument("--timeout-run", type=int, default=1800)
    ap.add_argument("--retries", type=int, default=1, help="retries of a cell that exits with an error (default 1)")
    ap.add_argument("--build-only", action="store_true")
    ap.add_argument("--skip-existing", action="store_true",
                    help="do not recompile a cell whose binary already exists (harness and adapters pinned)")
    ap.add_argument("--measure-only", action="store_true", help="reuse binaries from a previous build")
    ap.add_argument("--dry-run", action="store_true", help="list the cells and exit")
    ap.add_argument("--label", default="batch")
    ap.add_argument("--source-commit", help="commit of the adapter source (default: harness/SOURCE_COMMIT if present)")
    ap.add_argument("--node-name", default=socket.gethostname(),
                    help="node name for the batch meta (inside a container the hostname is the container id)")
    ap.add_argument("--arch-name", default="", help="b200 or gb200, from the lease line")
    args = ap.parse_args()

    variant = args.adapter
    control = args.control or variant
    if args.control_req and args.control_req not in REQ_CPP:
        raise SystemExit("--control-req must be one of %s" % ", ".join(REQ_CPP))
    harness_dir = os.path.abspath(args.harness)
    repo = os.path.abspath(args.repo)
    if args.root:
        args.work = args.work or os.path.join(args.root, "work", args.holder)
        args.out = args.out or os.path.join(args.root, "results", args.holder)
        args.lock = args.lock or os.path.join(args.root, "locks", "gpu%d.lock" % args.gpu)
    if not args.work or not args.out:
        raise SystemExit("--work and --out (or --root) are required")

    v_meta = read_adapter_meta(os.path.join(harness_dir, "adapters", variant + ".cuh"))
    c_meta = read_adapter_meta(os.path.join(harness_dir, "adapters", control + ".cuh"))
    if v_meta["scope"] != c_meta["scope"]:
        raise SystemExit("variant scope %s differs from control scope %s" % (v_meta["scope"], c_meta["scope"]))
    spec = json.load(open(args.cells))
    if args.named_cells:
        default_threads = {sc: v["threads"][0] for sc, v in spec["scopes"].items()}
        cells, skipped = expand_named_cells(args.named_cells, v_meta["scope"], args, default_threads)
        for name, why in skipped:
            log("skipping named cell %s: %s" % (name, why))
        spec = dict(spec, name="named")
    elif args.cell_list:
        items = json.load(open(args.cell_list))
        items = items if isinstance(items, list) else items.get("cells", [])
        cells = [{"key_type": c["key_type"], "threads": int(c["threads"]), "n": int(c["n"]), "k": int(c["k"]),
                  "requirement": c["requirement"]} for c in items if c.get("scope", v_meta["scope"]) == v_meta["scope"]]
        if args.keys:
            cells = [c for c in cells if c["key_type"] in args.keys.split(",")]
        spec = dict(spec, name="list")
    else:
        cells = expand_cells(spec, v_meta["scope"], args)
    if not cells:
        raise SystemExit("no cells after filtering")

    stamp = utc_now().strftime("%Y%m%d_%H%M%S")
    batch = "%s_vs_%s_%s_%s_%s" % (variant, control, spec.get("name", "cells"), args.label, stamp)
    gen_dir = os.path.join(args.work, "gen", "%s_vs_%s" % (variant, control))
    log_dir = os.path.join(args.work, "logs", batch)
    os.makedirs(gen_dir, exist_ok=True)
    os.makedirs(log_dir, exist_ok=True)
    os.makedirs(args.out, exist_ok=True)

    log("batch %s: %d cells, scope %s, patterns %s, regimes %s" % (batch, len(cells), v_meta["scope"],
                                                                       args.patterns, args.regimes))
    if args.dry_run:
        for c in cells:
            log("  " + cell_name(variant, control, c, args.control_req, args.runs))
        return 0

    # ---- generate + compile (outside the lock)
    extra_flags = shlex.split(args.extra_flags) if args.extra_flags else []
    builds = {}
    jobs = []
    canary_bin = os.path.join(gen_dir, "canary_main")
    if not args.measure_only and not (args.skip_existing and os.path.exists(canary_bin)):
        jobs.append(("canary_main", os.path.join(harness_dir, "canary_main.cu"), canary_bin))
    for c in cells:
        name = cell_name(variant, control, c, args.control_req, args.runs)
        src = os.path.join(gen_dir, name + ".cu")
        binary = os.path.join(gen_dir, name)
        c["name"] = name
        c["binary"] = binary
        if args.measure_only:
            continue
        if args.skip_existing and os.path.exists(binary):
            builds[name] = {"status": "ok", "seconds": 0, "log": os.path.join(gen_dir, name + ".ptxas.txt"),
                            "skipped_existing": True}
            continue
        with open(src, "w") as f:
            f.write(TU_TEMPLATE.format(
                variant=variant, control=control,
                control_include=('#include "adapters/%s.cuh"' % control) if control != variant else "",
                key=KEY_CPP[c["key_type"]], threads=c["threads"], n=c["n"], k=c["k"], req=REQ_CPP[c["requirement"]],
                creq=REQ_CPP[args.control_req or c["requirement"]]))
        jobs.append((name, src, binary))

    if jobs:
        log("compiling %d translation units with %d jobs (%s)" % (len(jobs), args.jobs, args.nvcc))
        t0 = time.time()
        with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as ex:
            futs = {}
            for name, src, binary in jobs:
                lf = os.path.join(gen_dir, name + ".ptxas.txt")
                futs[ex.submit(compile_one, args.nvcc, args.arch, repo, harness_dir, src, binary, lf,
                               args.timeout_compile, extra_flags)] = name
            for fut in concurrent.futures.as_completed(futs):
                name = futs[fut]
                builds[name] = fut.result()
                if builds[name]["status"] != "ok":
                    log("  %s: %s (%.0f s), see %s" % (name, builds[name]["status"], builds[name]["seconds"],
                                                       builds[name]["log"]))
        ok = sum(1 for b in builds.values() if b["status"] == "ok")
        log("compiled %d/%d in %.0f s" % (ok, len(jobs), time.time() - t0))
    else:
        for c in cells:
            builds[c["name"]] = {"status": "ok" if os.path.exists(c["binary"]) else "missing_binary",
                                 "seconds": 0, "log": os.path.join(gen_dir, c["name"] + ".ptxas.txt")}

    # static analysis per binary (also outside the lock)
    ptxas_by_cell, sass_by_cell = {}, {}
    for c in cells:
        if builds.get(c["name"], {}).get("status") != "ok":
            continue
        ptxas_by_cell[c["name"]] = parse_ptxas(os.path.join(gen_dir, c["name"] + ".ptxas.txt"))
        sass_by_cell[c["name"]] = sass_stats(args.cuobjdump, c["binary"])

    source_commit = args.source_commit
    if not source_commit:
        sc_file = os.path.join(harness_dir, "SOURCE_COMMIT")
        if os.path.exists(sc_file):
            source_commit = open(sc_file).read().strip() or None
    meta = {
        "source_commit": source_commit,
        "batch": batch,
        "label": args.label,
        "holder": args.holder,
        "timestamp": utc_now().isoformat(),
        "date": utc_now().strftime("%Y-%m-%d"),
        "node": {"hostname": args.node_name, "container_hostname": socket.gethostname(),
                 "nvcc_version": nvcc_version(args.nvcc), "gpu_index": args.gpu, "arch_flag": args.arch,
                 "arch": args.arch_name},
        "repo": git_info(repo),
        "harness": {"dir": harness_dir, "cells_file": os.path.abspath(args.cells),
                    "regimes": args.regimes, "patterns": args.patterns, "seeds": args.seeds,
                    "battery": not args.no_battery, "oracle_only": args.oracle_only},
        "adapter": v_meta,
        "control": c_meta,
        "control_is_aa": control == variant and not args.control_req,
        "control_req": args.control_req,
        "runs": args.runs,
        "build": builds,
    }
    if args.build_only:
        path = os.path.join(args.out, batch + ".build.json")
        json.dump(meta, open(path, "w"), indent=1)
        log("build-only, wrote %s" % path)
        return 0

    # ---- measure (inside the lock): canary, every cell x pattern, canary
    env = dict(os.environ)
    env["CUDA_VISIBLE_DEVICES"] = str(args.gpu)
    patterns = args.patterns.split(",")
    results = []
    canary = {}
    runnable = [c for c in cells if builds.get(c["name"], {}).get("status") == "ok"]
    with GpuLock(args.lock):
        def canary_run(tag):
            out = os.path.join(log_dir, "canary_%s.json" % tag)
            st, sec = run_binary(canary_bin, ["--out", out], os.path.join(log_dir, "canary.log"), 300, env)
            try:
                canary[tag] = json.load(open(out))
            except Exception:
                canary[tag] = {"status": st}
            log("canary %s: %s" % (tag, json.dumps(canary.get(tag))))

        if os.path.exists(canary_bin):
            canary_run("start")
        t0 = time.time()
        for c in runnable:
            for pat in patterns:
                out = os.path.join(log_dir, "%s__%s.json" % (c["name"], pat))
                regimes = args.regimes
                if c.get("named_regime") and c["named_regime"] != "both":
                    regimes = ",".join(r for r in args.regimes.split(",") if r == c["named_regime"]) or regimes
                extra = ["--out", out, "--pattern", pat, "--regimes", regimes, "--seeds", str(args.seeds)]
                if args.runs and args.runs > 1:
                    extra += ["--runs", str(args.runs)]
                if args.check_sorted:
                    extra.append("--check-sorted")
                if args.no_battery:
                    extra.append("--no-battery")
                if args.oracle_only:
                    extra.append("--oracle-only")
                st, sec = run_binary(c["binary"], extra, os.path.join(log_dir, c["name"] + ".log"),
                                     args.timeout_run, env)
                retries = 0
                while st.startswith("run_error") and retries < args.retries:
                    # a transient device error (CUDA error 46, device busy) kills a cell before its
                    # oracle, one retry after a pause has saved such cells, the log keeps both runs
                    retries += 1
                    time.sleep(5)
                    st, sec2 = run_binary(c["binary"], extra, os.path.join(log_dir, c["name"] + ".log"),
                                          args.timeout_run, env)
                    sec += sec2
                rec = {"cell": c, "pattern": pat, "status": st, "seconds": sec, "json": out, "retries": retries}
                try:
                    rec["data"] = json.load(open(out))
                except Exception:
                    rec["data"] = None
                    if st == "ok":
                        rec["status"] = "no_json"
                results.append(rec)
                tail = ""
                try:
                    tail = open(os.path.join(log_dir, c["name"] + ".log")).read().splitlines()[-1][:160]
                except Exception:
                    pass
                log("  [%s %.0fs] %s" % (rec["status"], sec, tail))
        if os.path.exists(canary_bin):
            canary_run("end")
        log("measured %d runs in %.0f s" % (len(results), time.time() - t0))

    # ---- merge
    out_cells, failed, unsupported = [], [], []
    for rec in results:
        c, d = rec["cell"], rec["data"]
        if d is None:
            failed.append({"cell": c["name"], "pattern": rec["pattern"], "reason": rec["status"]})
            continue
        if d.get("status") == "variant_unsupported":
            unsupported.append({"cell": c["name"], "reason": "variant does not support this cell"})
            continue
        if not d.get("variant", {}).get("oracle_passed", False):
            failed.append({"cell": c["name"], "pattern": rec["pattern"], "reason": "oracle_failed",
                           "failures": d.get("variant", {}).get("oracle_failures", [])})
        if d.get("oracle_selftest") is False:
            failed.append({"cell": c["name"], "pattern": rec["pattern"], "reason": "oracle_selftest_failed"})
            log("  WARNING oracle self-test false for %s (harness defect, the cell's numbers are not trusted)"
                % c["name"])
        ptx = ptxas_by_cell.get(c["name"], {})
        sas = sass_by_cell.get(c["name"], {})
        for side in ("variant", "control"):
            for reg in ("latency", "throughput"):
                blk = d.get(side, {}).get(reg)
                if blk:
                    refine_resources(blk["resources"], ptx, sas)
                    refine_resources(blk.get("resources_noop", {}), ptx, sas)
        for cell in d.get("cells", []):
            refine_resources(cell["resources"], ptx, sas)
            if c.get("workload_name"):
                cell["workload_name"] = c["workload_name"]
                cell["input_pattern"] = "named_workload" if cell.get("input_pattern") == "random" else cell["input_pattern"]
                cell["named_pattern"] = rec["pattern"]
            cell["raw"] = {
                "cell_json": rec["json"],
                "variant": d.get("variant"),
                "control": d.get("control"),
                "control_supported": d.get("control_supported"),
                "oracle_selftest": d.get("oracle_selftest"),
                "canary": d.get("canary"),
                "device": d.get("device"),
                "variant_static": d.get("variant_static"),
                "control_static": d.get("control_static"),
                "build": builds.get(c["name"]),
            }
            out_cells.append(cell)
        if "device" in d and "device" not in meta["node"]:
            meta["node"]["device"] = d["device"]
        if d.get("harness_version") and not meta.get("harness_version"):
            meta["harness_version"] = d["harness_version"]

    meta["canary"] = canary
    meta["cells"] = out_cells
    meta["failed"] = failed
    meta["unsupported"] = unsupported
    meta["runs"] = [{k: v for k, v in r.items() if k != "data"} for r in results]
    path = os.path.join(args.out, batch + ".json")
    json.dump(meta, open(path, "w"), indent=1)

    # compact summary
    log("batch json: %s" % path)
    log("cells with numbers: %d, failed: %d, unsupported: %d" % (len(out_cells), len(failed), len(unsupported)))
    for cell in out_cells:
        ctrl = ("%.4g" % cell["control_value"]) if "control_value" in cell else "none"
        res = cell["resources"]
        local = ""
        if res.get("stack_bytes") or res.get("stl_count") or res.get("ldl_count"):
            local = " LOCAL stack %sB stl %s ldl %s" % (res.get("stack_bytes", 0), res.get("stl_count", 0),
                                                       res.get("ldl_count", 0))
        log("  %-4s T%-3d N%-5d K%-4d %-20s %-10s %12.4g  ctrl %s  regs %s spill %s%s" % (
            cell["key_type"], cell["threads"], cell["n"], cell["k"], cell["requirement"], cell["regime"],
            cell["value"], ctrl, res.get("registers"), res.get("spill_bytes"), local))
    for f in failed:
        log("  FAILED %s %s: %s" % (f["cell"], f.get("pattern", ""), f["reason"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
